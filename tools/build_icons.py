"""Build _runtime/icons.js from the SVG icons in library/icons/<set>/.

Scenes load icons.js and write <i data-icon="rocket"></i>; modern.js swaps in the inline SVG, so the icon takes the
text colour (currentColor). Run this after you add icons (`anim.py lib icon ...` runs it for you).

    .venv/bin/python tools/build_icons.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ICONS = ROOT / "library" / "icons"
OUT = ROOT / "_runtime" / "icons.js"


def build() -> int:
    icons = {}
    for svg in sorted(ICONS.glob("*/*.svg")):
        text = re.sub(r"\s+", " ", svg.read_text(encoding="utf-8")).strip()
        text = re.sub(r'\s(width|height)="[^"]*"', "", text, count=2)  # size comes from CSS
        name = svg.stem if svg.parent.name == "lucide" else f"{svg.parent.name}/{svg.stem}"
        icons[name] = text
    body = json.dumps(icons, indent=0, sort_keys=True, ensure_ascii=False)
    OUT.write_text("// GENERATED by tools/build_icons.py from library/icons/. Do not edit.\n"
                   f"window.VF_ICONS = {body};\n", encoding="utf-8")
    return len(icons)


if __name__ == "__main__":
    print(f"{build()} icons -> {OUT.relative_to(ROOT)}")
